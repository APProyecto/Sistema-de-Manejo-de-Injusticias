import crypto from "crypto";

const ALGORITHM = "aes-256-gcm";
const IV_LENGTH = 12;

const encryptionKey = process.env.APP_ENCRYPTION_KEY;

if (!encryptionKey) {
  throw new Error("APP_ENCRYPTION_KEY is not defined");
}

const keyBuffer = Buffer.from(encryptionKey, "hex");

if (keyBuffer.length !== 32) {
  throw new Error("APP_ENCRYPTION_KEY must be 32 bytes in hex format");
}

/*
  Function: encryptText.
  Inputs:
    - text: String. Plain text to encrypt.
  Description: Encrypts plain text using AES-256-GCM.
  Outputs: Encrypted text in iv:authTag:encrypted format.
*/
export function encryptText(text: string) : string {
    const iv = crypto.randomBytes(IV_LENGTH);

    const cipher = crypto.createCipheriv(ALGORITHM, keyBuffer, iv);

    const encrypted = Buffer.concat([
        cipher.update(text, "utf-8"),
        cipher.final(),
    ]);

    const authTag = cipher.getAuthTag();
    return [
        iv.toString("hex"),
        authTag.toString("hex"),
        encrypted.toString("hex"),
    ].join(":");
}

/*
  Function: decryptText.
  Inputs:
    - encryptedText: String. Encrypted text generated by encryptText.
  Description: Decrypts AES-256-GCM encrypted text.
  Outputs: Original plain text.
*/
export function decryptText(encryptedText: string): string {
  const [ivHex, authTagHex, encryptedHex] = encryptedText.split(":");

  if (!ivHex || !authTagHex || !encryptedHex) {
    throw new Error("Invalid encrypted text format");
  }

  const decipher = crypto.createDecipheriv(
    ALGORITHM,
    keyBuffer,
    Buffer.from(ivHex, "hex")
  );

  decipher.setAuthTag(Buffer.from(authTagHex, "hex"));

  const decrypted = Buffer.concat([
    decipher.update(Buffer.from(encryptedHex, "hex")),
    decipher.final(),
  ]);

  return decrypted.toString("utf8");
}

/*
  Function: safeDecryptText.
  Inputs:
    - value: String. Possibly encrypted text.
  Description: Tries to decrypt a value. If it is not encrypted, returns the original value.
  Outputs: Decrypted text or original value.
*/
export function safeDecryptText(value: string): string {
  try {
    return decryptText(value);
  } catch {
    return value;
  }
}